#!/usr/bin/env python3
"""Convert supplied GLB meshes into small interleaved WebGPU vertex/index assets.
Preserves the original GLBs separately, and rasterizes their geometry rather than
approximating them with rotating sprites or CPU raycast boxes.
Requires numpy, trimesh, Pillow; run from the project with `python tools/convert_models.py`.
"""
import io, json, base64, struct, numpy as np, trimesh
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'assets'/'models'
ASSETS.mkdir(parents=True,exist_ok=True)

def material_color(name,kind):
    if kind=='slot': return [1.,1.,1.]
    if name=='Object_0': return [.36,.21,.10]
    return [1.,.40,.13]

def convert(kind,uv_step,pos_step):
    src=ASSETS/(kind+'.glb')
    scene=trimesh.load(str(src),force='scene',process=False)
    vertices=[];faces=[];offset=0
    for node in sorted(scene.graph.nodes_geometry):
        tf,name=scene.graph.get(node)
        mesh=scene.geometry[name]
        p=np.asarray(mesh.vertices,dtype=np.float32)
        p=(p@np.asarray(tf[:3,:3],dtype=np.float32).T+np.asarray(tf[:3,3],dtype=np.float32))
        norms=np.asarray(mesh.vertex_normals,dtype=np.float32)@np.linalg.inv(np.asarray(tf[:3,:3],dtype=np.float32)).T
        norms/=np.maximum(np.linalg.norm(norms,axis=1,keepdims=True),1e-7)
        # Trimesh scene transforms are Y-up for this campfire and Z-up for the slot.
        if kind=='campfire':p=p[:,[0,2,1]];norms=norms[:,[0,2,1]]
        uv=np.asarray(getattr(mesh.visual,'uv',None),dtype=np.float32)
        if uv.ndim!=2 or uv.shape[1]!=2 or len(uv)!=len(p):uv=np.zeros((len(p),2),dtype=np.float32)
        # Merge subpixel triangles using UV-aware clustering to preserve the label.
        if kind=='slot':
            key=np.concatenate([np.rint(p/pos_step).astype(np.int16),np.rint(uv/uv_step).astype(np.int16),np.rint(norms*3).astype(np.int16)],axis=1)
            _,mapping=np.unique(key,axis=0,return_inverse=True)
            n=int(mapping.max())+1
            count=np.maximum(np.bincount(mapping,minlength=n),1).astype(np.float32)
            averaged=lambda a:np.stack([np.bincount(mapping,weights=a[:,i],minlength=n)/count for i in range(a.shape[1])],axis=1).astype(np.float32)
            p=averaged(p);uv=averaged(uv);norms=averaged(norms)
            norms/=np.maximum(np.linalg.norm(norms,axis=1,keepdims=True),1e-7)
            f=mapping[np.asarray(mesh.faces,dtype=np.int32)]
            f=f[(f[:,0]!=f[:,1])&(f[:,1]!=f[:,2])&(f[:,0]!=f[:,2])]
        else:f=np.asarray(mesh.faces,dtype=np.int32)
        color=np.broadcast_to(np.array(material_color(name,kind),dtype=np.float32),(len(p),3)).copy()
        # Packed vertex: position xyz, normal xyz, UV xy, material colour RGB.
        vertices.append(np.concatenate([p,norms,uv,color],axis=1))
        faces.append(f+offset)
        offset+=len(p)
    v=np.concatenate(vertices);f=np.concatenate(faces)
    bounds_min=v[:,:3].min(axis=0);bounds_max=v[:,:3].max(axis=0)
    ranges=np.maximum(bounds_max-bounds_min,1e-6)
    size=np.array([.85,.67,.95] if kind=='slot' else [1.10,1.12,.46],dtype=np.float32)
    # Vertical origin is at the floor. The room's ceiling is at z=1.0.
    v[:,0]=(v[:,0]-(bounds_min[0]+bounds_max[0])/2)*size[0]/ranges[0]
    v[:,1]=(v[:,1]-(bounds_min[1]+bounds_max[1])/2)*size[1]/ranges[1]
    v[:,2]=(v[:,2]-bounds_min[2])*size[2]/ranges[2]
    vertex_data=v.astype('<f4').tobytes()
    index_data=f.astype('<u4').ravel().tobytes()
    binary=struct.pack('<4sII',b'CRM2',len(v),len(f)*3)+vertex_data+index_data
    (ASSETS/(kind+'-optimized.mesh')).write_bytes(binary)
    print(kind,'verts',len(v),'triangles',len(f),'optimized MiB',round(len(binary)/1024**2,2))
    return binary

campfire=convert('campfire',uv_step=.01,pos_step=.002)
slot=convert('slot',uv_step=.025,pos_step=.0075)

# Extract only the image used as the slot's base-color texture. Other textures
# are baked into a lightweight directional-light shader, avoiding 29MB of waste.
raw=(ASSETS/'slot.glb').read_bytes()
json_len=struct.unpack_from('<I',raw,12)[0]
doc=json.loads(raw[20:20+json_len])
chunk_offset=20+((json_len+3)//4)*4
bin_len=struct.unpack_from('<I',raw,chunk_offset)[0]
data=raw[chunk_offset+8:chunk_offset+8+bin_len]
view=doc['bufferViews'][doc['images'][0]['bufferView']]
image=Image.open(io.BytesIO(data[view['byteOffset']:view['byteOffset']+view['byteLength']])).convert('RGB')
image.thumbnail((768,768))
image.save(ASSETS/'slot-albedo.webp',format='WEBP',quality=89,method=6)
print('slot base-color texture',image.size)

js='// Generated by tools/convert_models.py from the two original user-supplied GLBs.\n'
js+='// Each payload starts with CRM2, a vertex count and an index count.\n'
js+='const CATROOMS_MODEL_MESHES={\n'
for kind,b in [('campfire',campfire),('slot',slot)]:
    js+=f" {kind}:'{base64.b64encode(b).decode('ascii')}',\n"
js+='};\n'
(ROOT/'js/graphics/model-data.js').write_text(js,encoding='ascii')
print('model-data.js size',round(len(js)/1024**2,2),'MiB')
