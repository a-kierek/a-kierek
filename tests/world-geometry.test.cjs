const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const ctx=vm.createContext({});const run=s=>vm.runInContext(s,ctx);
run(['js/graphics/shaders/shared.js','js/graphics/shaders/terrain.js','js/graphics/shaders/world-geometry.js','js/graphics/world-geometry.js'].map(read).join('\n'));
run(`let tiles=new Uint32Array(128*128); tiles.fill(1);tiles[129]=0; let v=buildWorldWallVertices(tiles,3);`);
assert.equal(run('v.length'),4*6*6);
assert.equal(run('Array.from(v).every(Number.isFinite)'),true);
assert.equal(run('Array.from({length:4},(_,i)=>Array.from(v.slice(i*36+3,i*36+6)).join(",")).join(";")'),'0,1,0;2,1,0;1,0,1;1,2,1');
run('tiles[130]=5;v=buildWorldWallVertices(tiles,3)');assert.equal(run('v.length'),6*6*6);
run('tiles[130]=4;v=buildWorldWallVertices(tiles,3)');assert.equal(run('v.length'),4*6*6);
run('tiles[130]=0;v=buildWorldWallVertices(tiles,3)');assert.equal(run('v.length'),6*6*6);
assert.equal(run('Array.from({length:v.length/6},(_,i)=>v[i*6+3]).includes(3)'),true);
assert.throws(()=>run('buildWorldWallVertices(tiles,129)'));
assert.equal(run('geometryTerrainSource().includes("for(var i:i32=0;i<190;i++)")'),false);
assert.equal(run('TERRAIN_WGSL.includes("for(var i:i32=0;i<190;i++)")'),true);
assert.equal(run('geometryTerrainSource().includes("textureLoad(geometryHits")'),true);
assert.equal(run('geometryTerrainSource().includes("if(hasWall){")'),true);
assert.equal(run('geometryTerrainSource().includes("sceneryAt(pixel.xy,ray3)")'),true);
run('tiles.fill(0);v=buildWorldWallVertices(tiles,128)');assert.equal(run('v.length'),128*4*6*6);
run('tiles.fill(1);v=buildWorldWallVertices(tiles,128)');assert.equal(run('v.length'),0);
console.log('PASS raster wall mesh, collision-only tiles, door changes, boundary walls and shader contracts');
